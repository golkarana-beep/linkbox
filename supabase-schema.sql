-- Keep the owner UID below aligned with the UID used by the existing linkbox_content policies.
-- If you already ran the previous schema, run this file again; it is designed to be re-runnable.
create table if not exists public.linkbox_content (
  id integer primary key check (id = 1),
  data jsonb not null default '{"categories":[{"id":"all","name":"همه لینک‌ها","isSystem":true,"color":"#4f6ef7"}],"links":[],"theme":"light","activeCategory":"all","updatedAt":0}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.linkbox_content enable row level security;
drop policy if exists "Public can read linkbox" on public.linkbox_content;
create policy "Public can read linkbox" on public.linkbox_content for select to anon, authenticated using (true);
drop policy if exists "Only owner can insert linkbox" on public.linkbox_content;
create policy "Only owner can insert linkbox" on public.linkbox_content for insert to authenticated with check ((select auth.uid()) = 'c8e4e368-a1e4-401e-b593-e2763867c091'::uuid);
drop policy if exists "Only owner can update linkbox" on public.linkbox_content;
create policy "Only owner can update linkbox" on public.linkbox_content for update to authenticated using ((select auth.uid()) = 'c8e4e368-a1e4-401e-b593-e2763867c091'::uuid) with check ((select auth.uid()) = 'c8e4e368-a1e4-401e-b593-e2763867c091'::uuid);
grant usage on schema public to anon, authenticated;
grant select on public.linkbox_content to anon, authenticated;
grant insert, update on public.linkbox_content to authenticated;

-- Anonymous, privacy-minimized usage events. No IP address or personal profile is stored.
create table if not exists public.linkbox_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('page_view','link_click')),
  link_id text,
  link_title text,
  category_id text,
  visitor_id text,
  created_at timestamptz not null default now()
);
create index if not exists linkbox_events_created_at_idx on public.linkbox_events(created_at desc);
create index if not exists linkbox_events_type_idx on public.linkbox_events(event_type, created_at desc);
create index if not exists linkbox_events_link_idx on public.linkbox_events(link_id, created_at desc);
alter table public.linkbox_events enable row level security;
drop policy if exists "Anyone can record LinkBox events" on public.linkbox_events;
create policy "Anyone can record LinkBox events" on public.linkbox_events for insert to anon, authenticated with check (event_type in ('page_view','link_click') and (visitor_id is null or length(visitor_id) <= 100) and (link_title is null or length(link_title) <= 300));
drop policy if exists "Only owner can read LinkBox events" on public.linkbox_events;
create policy "Only owner can read LinkBox events" on public.linkbox_events for select to authenticated using ((select auth.uid()) = 'c8e4e368-a1e4-401e-b593-e2763867c091'::uuid);
grant insert on public.linkbox_events to anon, authenticated;
grant select on public.linkbox_events to authenticated;

